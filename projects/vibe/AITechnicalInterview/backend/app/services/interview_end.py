"""Признаки завершения интервью агентом."""

_END_PHRASES = (
    "завершаем интервью",
    "интервью заверш",
    "на этом закончим",
    "на этом всё",
    "на этом все",
    "закончили интервью",
    "можете нажать «завершить»",
    "можете нажать завершить",
    "кнопку завершить",
    "завершить интервью",
    "заканчиваем собеседование",
    "спасибо за интервью",
    "больше вопросов нет",
    "вопросов больше нет",
)


def ai_signals_interview_end(message: str, *, turn_end_flag: bool = False) -> bool:
    if turn_end_flag:
        return True
    t = (message or "").lower()
    return any(p in t for p in _END_PHRASES)
